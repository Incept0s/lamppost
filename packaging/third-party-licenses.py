def main(output: str) -> None:
    metadata = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--manifest-path", str(ROOT / "panel" / "Cargo.toml")],
        check=True, capture_output=True, text=True).stdout)
    used = {node["id"] for node in metadata["resolve"]["nodes"]}
    crates = sorted(
        (p for p in metadata["packages"] if p["id"] in used and p["name"] != "lamppost-control"),
        key=lambda p: (p["name"], p["version"]),
    )

    seen = {}          # text hash -> crate that printed it first
    apache_texts = []
    out = []
    out.append("Third-party licences of the LAMPPost control panel\n")
    out.append("=" * 52 + "\n\n")
    out.append(f"The lamppost-control binary contains {len(crates)} Rust crates. Their\n")
    out.append("licence notices follow. Where a crate offers a choice of licences, LAMPPost\n")
    out.append("uses it under the permissive option (MIT or Apache-2.0).\n")
    missing = []
    for crate in crates:
        label = f"{crate['name']} {crate['version']}"
        licence = crate.get("license") or crate.get("license_file") or "unknown"
        out.append("\n" + "-" * 78 + "\n")
        out.append(f"{label}\nLicence: {licence}\n")
        if crate.get("authors"):
            out.append(f"Authors: {', '.join(crate['authors'])}\n")
        if crate.get("repository"):
            out.append(f"Source:  {crate['repository']}\n")
        files = licence_files(pathlib.Path(crate["manifest_path"]).parent)
        if not files:
            missing.append(label)
            out.append("(No licence file in the crate: the standard text of the licence named\n"
                       " above applies, printed at the end of this file; copyright holders are\n"
                       " the authors listed.)\n")
        for path in files:
            text = path.read_text(errors="replace").strip()
            digest = hashlib.sha256(text.encode()).hexdigest()
            if digest in seen:
                out.append(f"\n[{path.name}: same text as printed for {seen[digest]}]\n")
                continue
            seen[digest] = label
            if "apache" in path.name.lower():
                apache_texts.append(text)
            out.append(f"\n[{path.relative_to(pathlib.Path(crate['manifest_path']).parent)}]\n{text}\n")

    # the standard texts for crates that only name their licence
    out.append("\n" + "=" * 78 + "\n")
    out.append("Standard licence texts\n")
    out.append("=" * 78 + "\n")
    out.append("\nMIT License (Copyright (c) the authors listed for each crate)\n\n" + MIT + "\n")
    apache = next((text for text in apache_texts if "Apache License" in text and "Version 2.0" in text), None)
    if apache:
        out.append("\nApache License 2.0\n\n" + apache + "\n")
    out.append("\n" + BSL + "\n")

    pathlib.Path(output).write_text("".join(out))
    print(f"{output}: {len(crates)} crates, {len(seen)} distinct licence texts"
          + (f", {len(missing)} without a licence file" if missing else ""))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "THIRD-PARTY-LICENSES.txt")
