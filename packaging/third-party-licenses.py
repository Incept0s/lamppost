#!/usr/bin/env python3
"""Write the licence texts of every Rust crate built into the control panel.

The crates' licences (MIT, Apache-2.0, BSD, Zlib, ...) allow redistribution on
the condition that their notices travel with the binary. The packaging
scripts call this and ship the result as THIRD-PARTY-LICENSES.txt.

    packaging/third-party-licenses.py <output file>

Needs "cargo" and the crate sources (present after "cargo build").
"""
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PATTERNS = ("licen", "copying", "notice", "unlicense", "ofl", "ufl")


SKIP_DIRS = {"src", "tests", "benches", "examples", "target", ".git", ".github"}


def licence_files(directory: pathlib.Path):
    """Licence files in the crate root and one folder below (fonts/, LICENSES/, ...)."""
    files = []
    folders = [directory] + sorted(
        d for d in directory.iterdir() if d.is_dir() and d.name not in SKIP_DIRS
    )
    for folder in folders:
        for path in sorted(folder.iterdir()):
            name = path.name.lower()
            if path.is_file() and (name.startswith(PATTERNS) or "license" in name or "licence" in name) \
                    and not name.endswith((".rs", ".toml", ".py", ".sh")):
                files.append(path)
    return files


